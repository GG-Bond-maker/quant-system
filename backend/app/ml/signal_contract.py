"""Canonical inference metadata and point-in-time signal eligibility checks."""
from __future__ import annotations

import hashlib
import json
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any
from uuid import uuid4

import numpy as np
import pandas as pd

from .calibration import calibrated_values
from .infer import predict_with_contrib


def model_metadata(model_dir: Path) -> dict[str, Any]:
    """Fail closed when a model's horizon or information cutoff is unknown."""
    metrics = json.loads((model_dir / "metrics.json").read_text(encoding="utf-8"))
    horizon = int(metrics["horizon"])
    if horizon <= 0:
        raise ValueError("模型预测期限无效")
    split = metrics.get("split") or {}
    fit_end, valid_end = split.get("train_end"), split.get("valid_end")
    if not fit_end or not valid_end:
        raise ValueError("模型缺少训练/验证截止日，无法验证历史信号")
    available = metrics.get("model_available_on")
    if available is None:
        # Legacy models already record training timestamps in their version names.
        match = re.search(r"(20\d{6})_\d{6}", model_dir.name)
        if match is None:
            raise ValueError("模型缺少可用时点，请重新训练带时点元数据的模型")
        available = datetime.strptime(match.group(1), "%Y%m%d").date().isoformat()
    minimum = max(pd.Timestamp(available), pd.Timestamp(split.get("test_start") or available))
    if minimum <= pd.Timestamp(valid_end) or pd.Timestamp(fit_end) > pd.Timestamp(valid_end):
        raise ValueError("模型训练/验证/可用日期顺序无效")
    basis = metrics.get("train_basis") or {}
    feature_version = basis.get("feature_version") or metrics.get("feature_version")
    if feature_version is None:
        import sqlite3
        from ..core.config import get_settings
        path = get_settings().SQLITE_PATH
        if path.exists():
            with sqlite3.connect(f"file:{path.as_posix()}?mode=ro", uri=True) as conn:
                row = conn.execute("SELECT feature_version FROM model_registry WHERE version=?",
                                   (metrics.get("version", model_dir.name),)).fetchone()
                feature_version = row[0] if row else None
    if not feature_version:
        raise ValueError("模型缺少特征版本来源，请重新训练或修复注册表")
    return {"model_version": model_dir.name,
            "feature_version": feature_version,
            "label_horizon": horizon, "fit_end": str(fit_end)[:10],
            "validation_end": str(valid_end)[:10], "model_available_on": minimum.date().isoformat(),
            "dataset_version": metrics.get("dataset_version", ""),
            "target_basis": basis.get("target", "unknown"),
            "evaluation_kind": metrics.get("evaluation_kind", "live")}


def validate_signals(frame: pd.DataFrame) -> None:
    """Reject signals that could not have been generated by then-available models."""
    required = {"date", "symbol", "model_version", "feature_version", "label_horizon",
                "fit_end", "validation_end", "model_available_on", "signal_id", "run_id"}
    missing = required - set(frame.columns)
    if missing:
        raise ValueError(f"信号缺少时点/版本元数据 {sorted(missing)}；请用统一推理入口重新生成")
    if frame.empty:
        raise ValueError("信号为空")
    for name in required:
        if frame[name].isna().any():
            raise ValueError(f"信号元数据 {name} 存在缺失")
    dates = pd.to_datetime(frame["date"], errors="coerce")
    available = pd.to_datetime(frame["model_available_on"], errors="coerce")
    fit = pd.to_datetime(frame["fit_end"], errors="coerce")
    valid = pd.to_datetime(frame["validation_end"], errors="coerce")
    if dates.isna().any() or available.isna().any() or fit.isna().any() or valid.isna().any():
        raise ValueError("信号包含不可解析的时点")
    if ((dates < available) | (dates <= valid) | (available <= valid) | (valid < fit)).any():
        raise ValueError("拒绝前视信号：预测日早于模型可用时点或位于训练/验证区间")
    if (pd.to_numeric(frame["label_horizon"], errors="coerce").fillna(0) <= 0).any():
        raise ValueError("信号预测期限无效")


def predict_panel(panel: pd.DataFrame, booster: Any, features: list[str], model_dir: Path,
                  run_id: str | None = None) -> pd.DataFrame:
    """One inference implementation for CLI, scheduled jobs and research replay."""
    metadata = model_metadata(model_dir)
    output = panel[["date", "symbol"]].copy()
    for key, value in metadata.items():
        output[key] = value
    output["run_id"] = run_id or uuid4().hex
    output["signal_id"] = [hashlib.sha256(
        f"{metadata['model_version']}:{metadata['dataset_version']}:{str(day)[:10]}:{symbol}".encode()
    ).hexdigest()[:32] for day, symbol in zip(output["date"], output["symbol"], strict=True)]
    validate_signals(output)
    pred, _ = predict_with_contrib(booster, panel, features)
    output["pred_score"] = np.asarray(pred, dtype=float)
    output["signal_generated_at"] = datetime.now(timezone.utc).isoformat()
    calibration_path = model_dir / "calibration.json"
    artifact = json.loads(calibration_path.read_text(encoding="utf-8")) if calibration_path.exists() else {}
    calibrated = calibrated_values(np.asarray(pred), artifact)
    output["calibrated_probability"] = calibrated[0] if calibrated else np.nan
    output["prediction_lower"] = calibrated[1] if calibrated else np.nan
    output["prediction_upper"] = calibrated[2] if calibrated else np.nan
    output["interval_coverage_level"] = artifact.get("coverage_level")
    return output


def write_predictions(output: pd.DataFrame, directory: Path, *, replace: bool = False) -> list[Path]:
    """Persist per-day partitions without silently replacing immutable old signals."""
    from ..data.parquet_store import atomic_write_parquet

    validate_signals(output)
    directory.mkdir(parents=True, exist_ok=True)
    paths: list[Path] = []
    for day, rows in output.groupby(pd.to_datetime(output["date"]).dt.date):
        path = directory / f"date={day:%Y%m%d}.parquet"
        if path.exists() and not replace:
            old = pd.read_parquet(path)
            stable = ["date", "symbol", "model_version", "feature_version", "label_horizon", "pred_score"]
            left = old.reindex(columns=stable).sort_values("symbol").reset_index(drop=True)
            right = rows.reindex(columns=stable).sort_values("symbol").reset_index(drop=True)
            left["date"], right["date"] = pd.to_datetime(left["date"]), pd.to_datetime(right["date"])
            if not left.equals(right):
                raise ValueError(f"已有信号 {path.name} 与本次不同；历史实验须写入独立run目录")
        else:
            atomic_write_parquet(path, rows)
        paths.append(path)
    return paths
